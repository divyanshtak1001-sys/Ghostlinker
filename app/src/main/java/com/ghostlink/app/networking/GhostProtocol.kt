package com.ghostlink.app.networking

/**
 * GhostProtocol — the small application-level handshake that runs over an
 * established transport connection (Bluetooth RFCOMM today, Wi-Fi Direct later)
 * before any chat message is exchanged.
 *
 * ─── Why a handshake at all ─────────────────────────────────────────────────
 * A raw RFCOMM connection only proves that *a* Bluetooth device connected. The
 * handshake confirms the peer is actually running GhostLink, and it is how the
 * two devices learn each other's temporary alias. Nothing else is exchanged:
 *
 *   client -> server   "GHLK/1 HELLO <alias>"
 *   server -> client   "GHLK/1 ACK <alias>"
 *
 * ─── Privacy ────────────────────────────────────────────────────────────────
 * The only value carried in the handshake is the temporary in-memory alias
 * (for example "Shadow_7F3"). No account name, phone number, contact, MAC
 * address or persistent identifier is ever sent, and the alias is regenerated
 * per session by the existing alias generator.
 *
 * ─── Security note ──────────────────────────────────────────────────────────
 * The handshake identifies the peer's GhostLink alias only. It is NOT an
 * authenticated key exchange and it does NOT provide end-to-end encryption.
 * RFCOMM link encryption, when negotiated by the OS during pairing, protects
 * only the radio link between the two paired devices; it is not a substitute
 * for a separately implemented and verified end-to-end encryption layer.
 */
object GhostProtocol {

    const val TAG = "GHLK/1"
    const val HELLO = "HELLO"
    const val ACK = "ACK"
    const val BYE = "BYE"

    /**
     * The fixed request line the client sends first. The server recognises this
     * prefix, which is how a connection from a non-GhostLink app is rejected
     * instead of being mistaken for a peer.
     */
    const val HELLO_PREFIX = "$TAG $HELLO "

    /** The server's fixed acknowledgement prefix. */
    const val ACK_PREFIX = "$TAG $ACK "

    /**
     * Builds the client's opening handshake line.
     * [alias] must already be sanitised by the caller: aliases are generated by
     * GhostLink itself (letters, digits and underscore) and never come from the
     * user, but the newline strip below makes a forged value harmless.
     */
    fun buildHello(alias: String): String = "$TAG $HELLO ${sanitise(alias)}"

    /** Builds the server's acknowledgement line. */
    fun buildAck(alias: String): String = "$TAG $ACK ${sanitise(alias)}"

    /**
     * Extracts the peer alias from a HELLO or ACK line.
     * @return the alias, or null when [line] is not a valid GhostLink handshake.
     */
    fun parseHandshake(line: String): String? {
        val trimmed = line.trim()
        return when {
            trimmed.startsWith(HELLO_PREFIX) -> trimmed.removePrefix(HELLO_PREFIX).trim().ifEmpty { null }
            trimmed.startsWith(ACK_PREFIX) -> trimmed.removePrefix(ACK_PREFIX).trim().ifEmpty { null }
            else -> null
        }
    }

    /** True when [line] is the opening HELLO line a server expects from a client. */
    fun isHello(line: String): Boolean = line.trim().startsWith(HELLO_PREFIX)

    /**
     * Keeps a handshake value to a single short token so a malicious peer cannot
     * inject extra lines or an oversized alias into the session.
     */
    private fun sanitise(value: String): String =
        value.replace("\r", "")
            .replace("\n", "")
            .trim()
            .take(32)
}
